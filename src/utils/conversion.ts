import { jsPDF } from 'jspdf';
import { blobToDataUrl } from './compression';

export interface ConversionResult {
  blob: Blob;
  dataUrl: string;
  outputFormat: 'pdf' | 'jpeg' | 'png';
  outputFileName: string;
  sizeKb: number;
  previewUrl: string;
}

/**
 * Converts an image file to a clean, standard A4 PDF document for official portals.
 */
export async function convertImageToPdf(
  file: File | Blob,
  options: {
    fileName?: string;
    orientation?: 'portrait' | 'landscape';
    includeHeaderTitle?: string;
  } = {}
): Promise<ConversionResult> {
  const dataUrl = await blobToDataUrl(file);

  return new Promise((resolve, reject) => {
    const img = new Image();
    img.onload = () => {
      const orientation = options.orientation || (img.width > img.height ? 'landscape' : 'portrait');
      const doc = new jsPDF({
        orientation,
        unit: 'mm',
        format: 'a4',
      });

      const pageWidth = doc.internal.pageSize.getWidth();
      const pageHeight = doc.internal.pageSize.getHeight();
      const margin = 10; // 10mm margin

      const printableWidth = pageWidth - margin * 2;
      const printableHeight = pageHeight - margin * 2 - (options.includeHeaderTitle ? 15 : 0);

      // Maintain aspect ratio
      const imgRatio = img.width / img.height;
      let finalW = printableWidth;
      let finalH = finalW / imgRatio;

      if (finalH > printableHeight) {
        finalH = printableHeight;
        finalW = finalH * imgRatio;
      }

      // Center image
      const x = margin + (printableWidth - finalW) / 2;
      const y = margin + (options.includeHeaderTitle ? 12 : 0) + (printableHeight - finalH) / 2;

      if (options.includeHeaderTitle) {
        doc.setFont('helvetica', 'bold');
        doc.setFontSize(11);
        doc.setTextColor(51, 65, 85);
        doc.text(options.includeHeaderTitle, margin, margin + 4);
        doc.setFont('helvetica', 'normal');
        doc.setFontSize(8);
        doc.setTextColor(148, 163, 184);
        doc.text(`Converted via FormSaathi AI • ${new Date().toLocaleDateString()}`, margin, margin + 8);
      }

      // Add image to PDF
      const format = file.type.includes('png') ? 'PNG' : 'JPEG';
      doc.addImage(dataUrl, format, x, y, finalW, finalH, undefined, 'FAST');

      const pdfBlob = doc.output('blob');
      const pdfDataUrl = URL.createObjectURL(pdfBlob);
      const cleanName = (options.fileName || 'converted_document').replace(/\.[^/.]+$/, '') + '.pdf';

      resolve({
        blob: pdfBlob,
        dataUrl: pdfDataUrl,
        outputFormat: 'pdf',
        outputFileName: cleanName,
        sizeKb: Math.round((pdfBlob.size / 1024) * 10) / 10,
        previewUrl: pdfDataUrl,
      });
    };
    img.onerror = () => reject(new Error('Failed to load image for PDF conversion'));
    img.src = dataUrl;
  });
}

/**
 * Converts text / self-declaration into a certified PDF document
 */
export async function convertTextToPdf(
  title: string,
  content: string,
  applicantName?: string
): Promise<ConversionResult> {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 15;
  const maxLineWidth = pageWidth - margin * 2;

  // Header banner
  doc.setFillColor(30, 41, 59);
  doc.rect(0, 0, pageWidth, 24, 'F');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.setTextColor(255, 255, 255);
  doc.text(title.toUpperCase(), margin, 15);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(203, 213, 225);
  doc.text('OFFICIAL DECLARATION & SUPPORTING STATEMENT', margin, 20);

  // Body text
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(15, 23, 42);

  const lines = doc.splitTextToSize(content, maxLineWidth);
  doc.text(lines, margin, 38);

  // Footer / Signature block
  const footerY = 250;
  doc.setDrawColor(203, 213, 225);
  doc.line(margin, footerY, pageWidth - margin, footerY);

  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139);
  doc.text(`Generated by FormSaathi AI • Reusable Profile Document`, margin, footerY + 8);
  if (applicantName) {
    doc.text(`Applicant Name: ${applicantName}`, margin, footerY + 14);
    doc.text(`Date: ${new Date().toLocaleDateString('en-IN')}`, pageWidth - margin - 40, footerY + 14);
  }

  const pdfBlob = doc.output('blob');
  const pdfDataUrl = URL.createObjectURL(pdfBlob);
  const outName = `${title.toLowerCase().replace(/\s+/g, '_')}.pdf`;

  return {
    blob: pdfBlob,
    dataUrl: pdfDataUrl,
    outputFormat: 'pdf',
    outputFileName: outName,
    sizeKb: Math.round((pdfBlob.size / 1024) * 10) / 10,
    previewUrl: pdfDataUrl,
  };
}

/**
 * Converts image to alternate image format (e.g. PNG to JPEG or WebP to JPEG)
 */
export async function convertImageFormat(
  file: File | Blob,
  targetFormat: 'image/jpeg' | 'image/png' | 'image/webp'
): Promise<ConversionResult> {
  const dataUrl = await blobToDataUrl(file);

  return new Promise((resolve, reject) => {
    const img = new Image();
    img.onload = () => {
      const canvas = document.createElement('canvas');
      canvas.width = img.width;
      canvas.height = img.height;
      const ctx = canvas.getContext('2d');
      if (!ctx) return reject(new Error('Canvas context unavailable'));

      if (targetFormat === 'image/jpeg') {
        ctx.fillStyle = '#FFFFFF';
        ctx.fillRect(0, 0, img.width, img.height);
      }
      ctx.drawImage(img, 0, 0);

      canvas.toBlob(async (blob) => {
        if (!blob) return reject(new Error('Conversion failed'));
        const ext = targetFormat === 'image/jpeg' ? 'jpg' : targetFormat === 'image/png' ? 'png' : 'webp';
        const fileName = `converted_image.${ext}`;
        const outputDataUrl = URL.createObjectURL(blob);

        resolve({
          blob,
          dataUrl: outputDataUrl,
          outputFormat: ext as any,
          outputFileName: fileName,
          sizeKb: Math.round((blob.size / 1024) * 10) / 10,
          previewUrl: outputDataUrl,
        });
      }, targetFormat, 0.92);
    };
    img.onerror = () => reject(new Error('Failed to read image for format conversion'));
    img.src = dataUrl;
  });
}
